-- Min&Su Library setup for an empty database.
-- One run creates the tables, applies the migrations in order, and loads the seed.
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f db/setup_all.sql
--
-- Order:
--   db/schema.sql
--   db/migrations/002_remove_auth.sql
--   db/migrations/003_fix_dates.sql
--   db/seed.sql

-- ===== db/schema.sql =====

-- Min&Su Library schema.
-- Image columns store a path under public/assets/ or an absolute URL.
-- They never store the image bytes.
-- Running this file again is safe: existing tables are left as they are.
-- An older database that still has email and password_hash is updated by
-- db/migrations/002_remove_auth.sql, which init_db.py applies afterwards.

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name TEXT NOT NULL,
    slug TEXT NOT NULL,
    accent_color TEXT NOT NULL,
    CONSTRAINT users_slug_unique UNIQUE (slug)
);

CREATE TABLE IF NOT EXISTS chapters (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number INTEGER NOT NULL,
    title TEXT NOT NULL,
    subtitle TEXT,
    start_date DATE NOT NULL,
    end_date DATE,
    cover_image TEXT,
    intro_text TEXT,
    created_by INTEGER NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chapters_number_unique UNIQUE (number),
    CONSTRAINT chapters_number_positive CHECK (number >= 0),
    CONSTRAINT chapters_dates_ordered CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS photos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id INTEGER NOT NULL REFERENCES chapters (id) ON DELETE CASCADE,
    created_by INTEGER NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    image_path TEXT NOT NULL,
    caption TEXT,
    taken_on DATE
);

CREATE INDEX IF NOT EXISTS photos_chapter_id_idx ON photos (chapter_id);

CREATE TABLE IF NOT EXISTS trips (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id INTEGER NOT NULL REFERENCES chapters (id) ON DELETE CASCADE,
    created_by INTEGER NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    title TEXT NOT NULL,
    location TEXT,
    start_date DATE,
    end_date DATE,
    description TEXT,
    cover_photo TEXT,
    CONSTRAINT trips_dates_ordered CHECK (
        end_date IS NULL OR start_date IS NULL OR end_date >= start_date
    )
);

CREATE INDEX IF NOT EXISTS trips_chapter_id_idx ON trips (chapter_id);

-- happened_on is the calendar day of the date.
CREATE TABLE IF NOT EXISTS dates (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id INTEGER NOT NULL REFERENCES chapters (id) ON DELETE CASCADE,
    created_by INTEGER NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    title TEXT NOT NULL,
    place TEXT,
    happened_on DATE,
    description TEXT,
    rating SMALLINT,
    photo TEXT,
    CONSTRAINT dates_rating_range CHECK (rating IS NULL OR rating BETWEEN 1 AND 5)
);

CREATE INDEX IF NOT EXISTS dates_chapter_id_idx ON dates (chapter_id);

-- created_by is the author. Only that person may edit or delete the note.
CREATE TABLE IF NOT EXISTS notes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id INTEGER NOT NULL REFERENCES chapters (id) ON DELETE CASCADE,
    created_by INTEGER NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    body TEXT NOT NULL,
    written_on DATE,
    CONSTRAINT notes_body_not_blank CHECK (length(btrim(body)) > 0)
);

CREATE INDEX IF NOT EXISTS notes_chapter_id_idx ON notes (chapter_id);

CREATE TABLE IF NOT EXISTS achievements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id INTEGER NOT NULL REFERENCES chapters (id) ON DELETE CASCADE,
    created_by INTEGER NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    title TEXT NOT NULL,
    achieved_on DATE,
    description TEXT,
    photo TEXT,
    kind TEXT NOT NULL DEFAULT 'shared',
    CONSTRAINT achievements_kind_known CHECK (kind IN ('personal', 'shared'))
);

CREATE INDEX IF NOT EXISTS achievements_chapter_id_idx ON achievements (chapter_id);

